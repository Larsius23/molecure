"""Build the two steroid benchmark workspaces from the Coats CoMFA steroid SDF.

    python benchmarks/steroids/prepare.py ~/molecure_projects
    python benchmarks/steroids/prepare.py ~/molecure_projects --exclude S02

creates   steroids_cbg/   31 steroids: 21 training + 10 external   (corticosteroid-binding globulin)
          steroids_tbg/   21 steroids                              (testosterone-binding globulin)
(with --exclude, the same two workspaces without the named compounds, e.g. steroids_cbg_no_s02/)

What this script changes, and why (everything else is copied byte for byte):

  1. Source record 23 is dropped. Despite its name it is not cortisol 21-acetate: its SMILES is a
     ring-opened carboxylate anion. Record 32 is the correct compound.
  2. Activities are negated. The source stores log(1/K) numbers where MORE NEGATIVE means STRONGER
     binding (testosterone / TeBG = -9.2). The affinity constants K are association constants
     (M^-1), so log K = pKd, larger = stronger: pKd = -value.
  3. CBG values of steroids 16 and 17 are corrected from 5.225 to 5.255 (Coats 1998, Table 1:
     K = 0.18e6 M^-1, so log K = 5.2553). The original value stays in the `source_activity` tag.
  4. Every molecule gets a stable id from the paper's numbering: S01-S21 = Cramer Table I,
     T01-T10 = Cramer Figure 3 (the external set).

NOT changed: compound S02 (androstanediol) is structurally wrong in the source file (3-alpha-OH
where it should be 3-beta, and an undefined C17 that was built as 17-alpha). It stays in the
default workspaces so the "as distributed" benchmark can be run; use --exclude S02 to leave it out.

Pure Python on purpose: no RDKit, so the coordinates are never touched.
"""

import csv
import re
import sys
from pathlib import Path

SOURCE = Path(__file__).resolve().parent / "source" / "Coats_CoMFA_steroidsBenchmarkDataset.sdf"

N_TRAIN = 21  # source records 1-21 = Cramer's Table I
# Source records ("index" tag) in the order of Cramer's Figure 3, compounds 1-10.
# The source lists cortisol acetate twice: record 23 (wrong structure) and record 32 (correct).
EXTERNAL_ORDER = [22, 32, 24, 25, 26, 27, 28, 29, 30, 31]
# Coats (1998), Table 1 and text: the CBG affinity of steroids 16 and 17 is K = 0.18e6 M^-1,
# i.e. log K = 5.255. The source SDF (like several published reports) has 5.225. CBG data only.
CBG_CORRECTIONS = {16: 5.255, 17: 5.255}
RENAME = {
    "cortisolacetat": "cortisol_21_acetate",
    # cortisol is 11b,17,21-trihydroxy-4-pregnene-3,20-dione,
    # so these two are its 2a-methyl derivatives
    "11b,17,21-trihydroxy-2a-methyl-4-pregnen-3,20-dione": "2a_methylcortisol",
    "11b,17,21-trihydroxy-2a-methyl-9a-fluoro-4-pregnen-3,20-dione": "9a_fluoro_2a_methylcortisol",
}

# Same folder layout as `molecure init`.
SUBDIRS = ("data/raw", "data/curated", "data/screening", "data/reference", "splits", "runs")

PROJECT_YAML = """\
# Benchmark 0: Cramer et al. 1988 steroid set, __TARGET__.
# Settings follow Coats 1998 (leave-one-out, so the numbers are reproducible); the original
# Cramer 1988 choices are noted beside each one.
# See benchmarks/steroids/README.md and expected.yaml.
schema_version: 1

project:
  name: __NAME__
  description: "__DESCRIPTION__"

datasets:
  - id: steroids
    role: calibration
    file: data/curated/__NAME__.sdf
    id_col: compound_id
    activity_col: pKd
    endpoint: pKd              # log10 of the association constant K (M^-1)

alignment:
  mode: prealigned
  file: data/curated/__NAME__.sdf
  id_property: compound_id
  metadata:
    note: poses supplied pre-aligned (Cramer 1988 alignment rule); not generated by molecure

chemistry:
  charge_model: gasteiger    # both papers used Gasteiger-Marsili charges

molecular_fields:
  method: comfa
  grid: {spacing: 2.0, padding: 4.0}
  probe_charge: 1.0
  energy_cutoff_kcal: 30.0
  dielectric: distance

pls:
  n_components: 2            # both papers report the 2-component model
  scaling: block             # Coats 1998: "standard CoMFA scaling" (Cramer 1988: none)
  min_sigma: 2.0             # Coats 1998: drop columns with sigma < 2.0 kcal/mol (Cramer: none)

validation:
  split: __SPLIT__
  cv: {loo: true, group_kfold_k: 4, group_kfold_repeats: 20}   # Cramer 1988 used 4 random groups
  metrics: [q2, r2, q2_f1, ccc]

runtime:
  seed: 42
"""


def read_records(path: Path) -> list[dict]:
    """Split the SDF into records: the molfile lines (up to M  END) and the data tags."""
    records = []
    for block in path.read_text(encoding="utf-8").split("$$$$\n"):
        if not block.strip():
            continue
        lines = block.split("\n")
        end = next(i for i, line in enumerate(lines) if line.startswith("M  END"))
        tags, i = {}, end + 1
        while i < len(lines):
            match = re.match(r">\s*<([^>]+)>", lines[i])
            if match:
                i += 1
                value = []
                while i < len(lines) and lines[i].strip():
                    value.append(lines[i].strip())
                    i += 1
                tags[match.group(1)] = " ".join(value)
            i += 1
        records.append({"molfile": lines[: end + 1], "tags": tags})
    return records


def slug(name: str) -> str:
    text = RENAME.get(name, name).lower()
    return re.sub(r"[^a-z0-9]+", "_", text).strip("_")[:40].strip("_")


def write_record(
    handle, record: dict, compound_id: str, activity: float, subset: str, source_value: str
) -> None:
    tags = record["tags"]
    handle.write("\n".join([compound_id] + record["molfile"][1:]) + "\n")  # new title, rest as is
    for tag, value in (
        ("compound_id", compound_id),
        ("pKd", f"{activity:.3f}"),
        ("subset", subset),
        ("source_name", tags["name"]),
        ("source_index", tags["index"]),
        ("source_activity", source_value),
        ("isomericSMILES", tags["isomericSMILES"]),
    ):
        handle.write(f"> <{tag}>\n{value}\n\n")
    handle.write("$$$$\n")


def describe(target: str, n_train: int, n_test: int, exclude: set[str]) -> str:
    size = f"{n_train} training" + (f" + {n_test} external" if n_test else "")
    notes = []
    if exclude:
        notes.append(f"{', '.join(sorted(exclude))} excluded")
    if "S02" not in exclude:
        notes.append("S02 androstanediol is structurally wrong in the source")
    return f"{target}: {size} steroids ({'; '.join(notes)})"


def build_workspace(
    out_root: Path, base: str, activity_tag: str, with_external: bool, exclude: set[str]
) -> None:
    name = base + ("_no_" + "_".join(sorted(c.lower() for c in exclude)) if exclude else "")
    root = out_root / name
    if (root / "project.yaml").exists():
        raise SystemExit(f"{root / 'project.yaml'} already exists; refusing to overwrite it")
    by_index = {int(r["tags"]["index"]): r for r in read_records(SOURCE)}
    chosen = [(f"S{n:02d}", by_index[n], "train") for n in range(1, N_TRAIN + 1)]
    if with_external:
        chosen += [(f"T{n:02d}", by_index[i], "test") for n, i in enumerate(EXTERNAL_ORDER, 1)]
    unknown = exclude - {prefix for prefix, _, _ in chosen}
    if unknown:  # checked before anything is written, so a typo leaves no empty folders behind
        raise SystemExit(f"--exclude: no such compound(s) in {name}: {sorted(unknown)}")
    chosen = [item for item in chosen if item[0] not in exclude]
    for sub in SUBDIRS:
        (root / sub).mkdir(parents=True, exist_ok=True)

    members = []
    with open(root / "data/curated" / f"{name}.sdf", "w", encoding="utf-8") as handle:
        for prefix, record, subset in chosen:
            tags = record["tags"]
            compound_id = f"{prefix}_{slug(tags['name'])}"
            raw = tags[activity_tag]
            activity = -float(raw)
            if activity_tag == "pKi_CBG":
                activity = CBG_CORRECTIONS.get(int(tags["index"]), activity)
            write_record(handle, record, compound_id, activity, subset, raw)
            members.append((compound_id, subset))

    n_test = sum(1 for _, subset in members if subset == "test")
    if with_external:
        with open(root / "splits/paper_split.csv", "w", newline="", encoding="utf-8") as fh:
            writer = csv.writer(fh)
            writer.writerow(["compound_id", "subset"])
            writer.writerows(members)
        split = "{method: from_file, file: splits/paper_split.csv}"
    else:
        split = "{method: random, test_fraction: 0.0}   # no external set exists for this target"
    target = "CBG" if with_external else "TeBG"
    text = (
        PROJECT_YAML.replace("__TARGET__", target)
        .replace("__NAME__", name)
        .replace("__DESCRIPTION__", describe(target, len(members) - n_test, n_test, exclude))
        .replace("__SPLIT__", split)
    )
    (root / "project.yaml").write_text(text, encoding="utf-8")
    print(f"created {root}  ({len(members)} compounds)")


def main() -> None:
    args = sys.argv[1:]
    exclude: set[str] = set()
    if "--exclude" in args:
        i = args.index("--exclude")
        if i + 1 >= len(args):
            raise SystemExit("--exclude needs a value, e.g. --exclude S02")
        exclude = {code.strip().upper() for code in args[i + 1].split(",") if code.strip()}
        del args[i : i + 2]
    if len(args) != 1:
        raise SystemExit("usage: python prepare.py <output folder> [--exclude S02,...]")
    out_root = Path(args[0]).expanduser().resolve()
    build_workspace(out_root, "steroids_cbg", "pKi_CBG", with_external=True, exclude=exclude)
    build_workspace(out_root, "steroids_tbg", "pKi_TeBG", with_external=False, exclude=exclude)


if __name__ == "__main__":
    main()
